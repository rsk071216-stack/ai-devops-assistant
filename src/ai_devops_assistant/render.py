"""Markdown rendering of a Diagnosis for terminals, PR comments and issues.

Everything that originates from logs, plans or a model is treated as untrusted text:
prose goes through ``neutralize_markdown`` and quoted evidence is code-fenced.
"""

from __future__ import annotations

from ai_devops_assistant import __version__
from ai_devops_assistant.models import Diagnosis, Finding
from ai_devops_assistant.sanitize import fenced, inline_code, neutralize_markdown

MAX_BODY_CHARS = 60_000
_TITLES = {
    "ci": "CI failure triage",
    "k8s": "Kubernetes diagnosis",
    "terraform": "Terraform plan risk review",
}
_SEVERITY_ORDER = {"critical": 0, "high": 1, "medium": 2, "low": 3, "info": 4}
_SEVERITY_LABEL = {"critical": "CRITICAL", "high": "HIGH", "medium": "MEDIUM", "low": "LOW", "info": "INFO"}


def _numbered(items: list[str]) -> str:
    return "\n".join(f"{i}. {neutralize_markdown(s)}" for i, s in enumerate(items, 1))


def _commands_block(commands: list[str]) -> str:
    return fenced("\n".join(commands), "bash")


def _usage_line(d: Diagnosis) -> str:
    u = d.usage
    if u.llm_calls == 0:
        tokens = "no model call (0 tokens, $0.00)"
    else:
        cost = "unknown" if u.estimated_cost_usd is None else f"${u.estimated_cost_usd:.4f}"
        tokens = f"{u.input_tokens} in / {u.output_tokens} out tokens, est. cost {cost} (estimate)"
    red = sum(d.redactions.values())
    trunc = f"{d.sent_bytes} of {d.input_bytes} bytes analysed" + (
        " (truncated: head + error windows + tail)" if d.truncated else ""
    )
    return f"{tokens} | secrets redacted: {red} | {trunc}"


def _finding_section(f: Finding, *, explain: bool) -> list[str]:
    out = [f"### Root cause\n\n{neutralize_markdown(f.root_cause)}\n"]
    if f.fix_steps:
        out.append(f"### Suggested fix\n\n{_numbered(f.fix_steps)}\n")
    if f.suggested_commands:
        out.append(
            "Suggested commands (review before running, nothing is executed for you):\n\n"
            + _commands_block(f.suggested_commands)
            + "\n"
        )
    if f.suggested_patch:
        out.append(
            "Suggested change (illustrative diff, apply by hand):\n\n"
            + fenced(f.suggested_patch, "diff")
            + "\n"
        )
    if f.evidence:
        shown = f.evidence if explain else f.evidence[:2]
        ev = "\n".join(f"{e.source}: {e.excerpt}" for e in shown)
        out.append("<details><summary>Evidence</summary>\n\n" + fenced(ev) + "\n\n</details>\n")
    return out


def _terraform_body(d: Diagnosis, *, explain: bool) -> list[str]:
    if not d.findings:
        return [
            "No destructive changes, public exposure or IAM widening were detected by the deterministic checks.\n"
        ]
    rows = ["| Severity | Finding | Why it matters |", "| --- | --- | --- |"]
    ordered = sorted(d.findings, key=lambda f: _SEVERITY_ORDER.get(f.severity, 9))
    for f in ordered:
        rows.append(
            f"| {_SEVERITY_LABEL.get(f.severity, f.severity)} | {neutralize_markdown(f.title)} | "
            f"{neutralize_markdown(f.root_cause).replace('|', '/')} |"
        )
    out = ["\n".join(rows) + "\n"]
    fixes = [s for f in ordered for s in f.fix_steps]
    if fixes:
        unique = list(dict.fromkeys(fixes))
        out.append("### Reviewer checklist\n\n" + _numbered(unique) + "\n")
    if explain:
        ev = "\n".join(f"{f.rule_id}: " + "; ".join(e.excerpt for e in f.evidence) for f in ordered)
        out.append("<details><summary>Evidence</summary>\n\n" + fenced(ev) + "\n\n</details>\n")
    return out


def _ai_section(d: Diagnosis) -> list[str]:
    ai = d.ai
    if ai is None:
        return []
    out = [
        f"### AI analysis ({inline_code(ai.provider + ' / ' + ai.model)}, confidence {ai.confidence})\n",
        "> Generated by a language model from redacted evidence. It can be wrong. Verify before acting.\n",
        f"{neutralize_markdown(ai.root_cause)}\n",
    ]
    if ai.fix_steps:
        out.append(_numbered(ai.fix_steps) + "\n")
    if ai.suggested_commands:
        out.append(
            "Model-suggested commands (unverified, review first):\n\n"
            + _commands_block(ai.suggested_commands)
            + "\n"
        )
    if ai.flagged_commands:
        flagged = "\n".join(f"- {inline_code(c)}" for c in ai.flagged_commands)
        out.append(f"Commands flagged as risky:\n\n{flagged}\n")
    if ai.suggested_patch:
        out.append(
            "Model-suggested change (diff, apply by hand):\n\n" + fenced(ai.suggested_patch, "diff") + "\n"
        )
    if ai.grounded_quotes:
        out.append(
            "<details><summary>Verified evidence quotes</summary>\n\n"
            + fenced("\n".join(ai.grounded_quotes))
            + "\n\n</details>\n"
        )
    return out


def _explain_section(d: Diagnosis) -> list[str]:
    lines = [
        "### How this diagnosis was reached (`--explain`)\n",
        f"1. Input: {d.input_bytes} bytes; sent for analysis: {d.sent_bytes} bytes; truncated: {'yes' if d.truncated else 'no'}.",
        "2. Secrets redacted before analysis: "
        + (", ".join(f"{k} x{v}" for k, v in d.redactions.items()) if d.redactions else "none found")
        + ".",
    ]
    if d.findings:
        lines.append("3. Deterministic rules matched (highest priority first):")
        for f in d.findings[:5]:
            lines.append(f"   - {inline_code(f.rule_id)} -> {f.category.value} ({f.confidence} confidence)")
            for e in f.evidence[:3]:
                lines.append(f"     - {e.source}: {inline_code(e.excerpt[:160])}")
    else:
        lines.append("3. No deterministic rule matched this input.")
    lines.append(
        "4. Model: "
        + (
            f"{d.ai.provider}/{d.ai.model}, output validated against a strict schema, {len(d.ai.grounded_quotes)} quote(s) verified, "
            f"{d.ai.ungrounded_quotes} dropped."
            if d.ai
            else "not used."
        )
    )
    lines.append(f"5. Final category: {inline_code(d.category.value)} ({d.confidence}); mode: {d.mode}.")
    return ["\n".join(lines) + "\n"]


def render_markdown(
    d: Diagnosis,
    *,
    explain: bool = False,
    run_url: str | None = None,
    marker: str | None = None,
    updated_note: str | None = None,
) -> str:
    parts: list[str] = []
    if marker:
        parts.append(f"<!-- {marker} -->")
    parts.append(f"## {_TITLES[d.kind]}: {neutralize_markdown(d.summary)}\n")
    meta = [
        f"Category: {inline_code(d.category.value)}",
        f"Confidence: **{d.confidence}**",
        f"Mode: **{d.mode}**",
    ]
    if run_url:
        meta.append(f"[Failed run]({run_url})")
    parts.append(" | ".join(meta) + "\n")
    if updated_note:
        parts.append(f"_{neutralize_markdown(updated_note)}_\n")

    if d.kind == "terraform":
        parts.extend(_terraform_body(d, explain=explain))
    elif d.primary is not None:
        parts.extend(_finding_section(d.primary, explain=explain))
        others = d.findings[1:3]
        if others:
            lines = "\n".join(f"- {neutralize_markdown(f.title)} ({inline_code(f.rule_id)})" for f in others)
            parts.append(f"### Other signals in the same input\n\n{lines}\n")
    elif d.ai is None:
        parts.append(
            "No known failure signature matched. Without a model there is no further analysis; "
            "configure a provider to analyse unfamiliar failures.\n"
        )

    parts.extend(_ai_section(d))
    if explain:
        parts.extend(_explain_section(d))
    if d.notices:
        parts.append("\n".join(f"> Note: {neutralize_markdown(n)}" for n in d.notices) + "\n")
    parts.append(
        "---\n"
        f"<sub>ai-devops-assistant {__version__} | {_usage_line(d)} | Suggestions are never applied automatically: "
        "a human decides.</sub>\n"
    )
    body = "\n".join(parts)
    if len(body) > MAX_BODY_CHARS:
        body = (
            body[: MAX_BODY_CHARS - 200] + "\n\n_(output truncated to fit the GitHub comment size limit)_\n"
        )
    return body
